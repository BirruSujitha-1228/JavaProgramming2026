package operators;

public class SwappingWithXOR {

	public static void main(String[] args) {
		//Normal Addition
		int a=10;
		int b=20;
		System.out.println("before swapping : a = "+a+" , b = "+b );
		b=b-a;
		a=b+b;
		System.out.println("After  swapping : a = "+a+" , b = "+b );
        //XOR 
		
	}

}
